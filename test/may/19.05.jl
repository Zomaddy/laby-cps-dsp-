function rozwiazanie(;
    x::Vector{Float64} = [-3.69, -3.9, -4.6, 0.14, 0.47, 4.32, -3.61, 1.39, -1.71, -1.6, -3.26, 2.25, 3.65, -1.89, 4.97, 4.57, 2.65, 4.85, 4.9, 4.84, -0.33, 2.29, 2.5, 4.95, 1.63, -4.8, -2.66, 0.56, 1.19, -0.66, -0.41, 3.05, 0.64, 0.93, 1.04, -4.06, 3.21, -3.09, -2.89, 1.26, -2.39, 1.65, 2.75, 3.79, 1.24, -4.81, -2.06, 4.57, 2.75, -1.86, 0.81, 3.71, 4.03, -0.2, -0.98, 0.01, -4.9, -3.97, -3.73, 1.2, -4.67],
    h::Vector{Float64} = [0.91, 2.78, 3.26, -4.34, 0.68, 1.19, -4.73, -1.78, -1.46, 3.26, -0.02, 1.43, 0.32, 3.84],
)

    N = length(x) + length(h) - 1
    y = zeros(Float64, N)

    for i in 1:length(x)
        for j in 1:length(h)
            y[i + j - 1] += x[i] * h[j]
        end
    end

    power = sum(y .^ 2) / N
    return power
end

