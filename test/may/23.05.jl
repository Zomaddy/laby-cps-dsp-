function rozwiazanie(;
    x::Vector{Float64} = [-3.9, 3.56, 2.71, -2.91, -2.44, -4.48, -1.37, -3.47, -4.99, 4.84, 0.23, 2.08, -1.4, 2.08, -2.42, 4.84, -0.64, 0.83, 2.58, 1.05, 2.23, 1.19, -3.62, 4.11, 4.18, 4.31, -2.41, 0.92, -2.14, 0.54, 3.6, -3.87, -4.46, 0.98, -2.14, -1.73, 3.38, -0.5, 3.08, -2.56, -2.13, -1.07, -2.3, 2.18, 2.64, 4.09, -4.9, 2.9, -2.15, -3.01, 2.8, 2.46, 1.08, 0.15, -4.04, 1.92, -0.32, 1.24, -3.66, 3.87, -4.87, -4.38, -0.7, -2.39],
    h::Vector{Float64} = [3.37, -1.4, -2.66, 0.11, -1.23, 0.08, -4.49, 2.52, -0.36, -3.14],
)
    N = length(x) + length(h) - 1
    y = zeros(Float64, N)

    for i in 1:length(x)
        for j in 1:length(h)
            y[i + j - 1] += x[i] * h[j]
        end
    end

    power = sum(y .^ 2) / N
    return power
end

