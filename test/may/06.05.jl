    x::Vector{Float64} = [1.5, -0.63, -2.02, -0.09, -1.94, -4.36, 2.17, 4.77, 4.43, -1.5, -3.53, 3.79, -1.99, 3.02, -3.31, 4.17, 1.77, 4.7, -4.75, -1.66, -0.03, 2.5, -2.33, 4.86, -1.14, -4.07, -4.03, -0.92, 3.38, 0.66, -4.08, 0.28, 0.22, 0.1, 2.54, -0.89, 0.4, -3.9, -4.63, 4.45, -2.96, 3.61, -4.22, -0.42, 2.79, 4.41, -4.87, -3.07, -1.44, -4.79, 0.88, 0.22, 4.76, -4.75, 1.54, 2.72, -2.94, -3.78, -4.59, 3.35, -3.59, 1.65, -4.73],
    h::Vector{Float64} = [0.12, 1.29, -2.87, -3.13, 3.14, -4.34, 4.96, 0.48, -4.21, 3.57, -1.08, 0.87, -4.87, -3.13, -4.1, 1.93, -1.99, 2.04, -3.61, 3.72, -0.51],
)

    N = length(x) + length(h) - 1       #długość wyniku splotu

    y = zeros(Float64, N)       #przygotowanie wektora wynikowego

    for i in 1:length(x)
    
        for j in 1:length(h)
            y[i + j - 1] += x[i] * h[j]
        end
    end

    rms = sqrt(sum(y .^2) / N)

    return rms
end

