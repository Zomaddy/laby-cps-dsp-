)
    n = 9
    poziomy_kwant = 2^n
    q = (b-a)/(poziomy_kwant - 1)

    suma_blad_kw = 0.0
    N = length(x)

    for i in 1:N
        value = max(a, min(b, x[i]))
        index = round((value-a)/q)
        index = max(0.0, min(Float64(poziomy_kwant - 1),index))

        x_q = a + index*q

        e = x_q - x[i]

        suma_blad_kw += e^2

    end
            
    rms_bledu = sqrt(suma_blad_kw/N)

    return rms_bledu

end
