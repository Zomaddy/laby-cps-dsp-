    L::Int = 73,
)
    y = zeros(Float64, L)

    for n in 1:L
        sum_x = 0.0

        for m in 1:length(b)
            idx_x = n - m + 1

            if 1 <= idx_x <= length(x)
                sum_x += b[m] * x[idx_x]
            end
        end

        sum_y = 0.0

        for k in 2:length(a)
            idx_y = n - k + 1

            if 1 <= idx_y
                sum_y += a[k] * y[idx_y]
            end
        end
 
        y[n] = (sum_x - sum_y) / a[1]
    end

    energy = sum(y .^ 2)
    return energy
end

