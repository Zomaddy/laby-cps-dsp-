function rozwiazanie(;
    b::Vector{Float64} = [0.009442423674654674, -0.054428634611531836, 0.1644395059018756, -0.34127927248627643, 0.5436734372591422, -0.7035136336652519, 0.7638719919555885, -0.7035136336652519, 0.5436734372591422, -0.34127927248627643, 0.16443950590187553, -0.0544286346115318, 0.009442423674654669],
    a::Vector{Float64} = [1.0, -6.625067137714334, 22.781107779894164, -51.85958489468712, 86.15268827990602, -109.21198465773992, 108.01469849128299, -83.85160414573258, 50.777898891271235, -23.45611471381487, 7.90466389895065, -1.7632306219419405, 0.20446599750956973],
