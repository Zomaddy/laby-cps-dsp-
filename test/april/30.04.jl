function rozwiazanie(;
    a::Float64 = -2.5,
    b::Float64 = 5.1,
    x::Vector{Float64} = [0.54, 0.79333, 1.04667, 1.3, 1.55333, 1.80667, 2.06, 2.31333, 2.56667, 2.82, 3.07333, 3.32667, 3.58, 3.83333, 4.08667, 4.34, 4.59333, 4.84667, 5.1, 4.84667, 4.59333, 4.34, 4.08667, 3.83333, 3.58, 3.32667, 3.07333, 2.82, 2.56667, 2.31333, 2.06, 1.80667, 1.55333, 1.3, 1.04667, 0.79333, 0.54, 0.28667, 0.03333, -0.22, -0.47333, -0.72667, -0.98, -1.23333, -1.48667, -1.74, -1.99333, -2.24667, -2.5, -2.24667, -1.99333, -1.74, -1.48667, -1.23333, -0.98, -0.72667, -0.47333, -0.22, 0.03333],
)
    n = 7
    poziomy_kwant = 2^n
    q = (b-a)/(poziomy_kwant-1)

    suma_blad_kw = 0.0

    N = length(x)

    for i in 1:N
        value = max(a, min(b,x[i]))
        index = round((value-a)/q)
        index = max(0.0, min(Float64(poziomy_kwant-1), index))

        x_q = a + index*q

        e = x_q - x[i]

        suma_blad_kw += e^2

    end

    moc_bledu = suma_blad_kw/N

    return moc_bledu
end
