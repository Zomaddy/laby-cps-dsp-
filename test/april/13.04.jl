function rozwiazanie(;
    zz::Vector{ComplexF64} = ComplexF64[0.21357861979027343 - 0.9769258790555618im, 0.6508752058561522 + 0.7591847379931393im, 0.21357861979027343 + 0.9769258790555618im, 0.6508752058561522 - 0.7591847379931393im, -0.0882576330744583 - 0.9960976810554748im, 0.7940214960121618 + 0.6078896806745518im, -0.0882576330744583 + 0.9960976810554748im, 0.7940214960121618 - 0.6078896806745518im],
    pp::Vector{ComplexF64} = ComplexF64[0.5779663295657219 + 0.8021020505785035im, 0.3093081295765918 - 0.9369860828597895im, 0.5779663295657219 - 0.8021020505785035im, 0.3093081295765918 + 0.9369860828597895im, 0.5009691413901568 + 0.8181134821011605im, 0.37586207707634783 - 0.8792335661228037im, 0.5009691413901568 - 0.8181134821011605im, 0.37586207707634783 + 0.8792335661228037im],
    k::Float64 = 0.008543987473786227,
    F::Vector{Float64} = [0.04, 0.13, 0.16, 0.2, 0.26, 0.36],
)

    sum_phase = 0.0

    for f in F
        z = exp(2.0 * im * pi * f)
        num = prod(z .- zz)
        denum = prod(z .- pp)
        H_z = k * (num / denum)
        phase = angle(H_z)
        
        sum_phase += phase
    end

    return sum_phase / length(F)
end

