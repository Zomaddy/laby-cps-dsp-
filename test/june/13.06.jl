function rozwiazanie(;
    x::Vector{Float64} = [2.46, 2.99, 2.89, 4.47, 3.64, 0.5, 4.46, -4.28, -1.91, -2.59, 0.65, -4.73, 0.65, 2.17, 2.54, -4.75, 3.63, 2.96, 4.86, 2.47, 1.02, 1.57, -1.32, 0.47, 3.01, 4.73, 2.89, -3.12, -3.62, -0.46, -4.04, -1.76, -4.27, -2.74, -4.75, 3.44, 3.01, 0.36, 2.36, -1.91, -2.04, 2.62, -4.93, 4.59, 2.89, -3.22, 2.92, -2.12, 3.29, 1.32, 0.32, -3.21, 4.46, 2.23, -1.91, 3.35, -2.59, 0.4, -1.9, -4.41, 4.7, -4.96],
    h::Vector{Float64} = [-4.96, -1.54, 3.66, 4.64, -4.96, -0.31, 1.42, 3.02, 1.3, 3.77, -3.98],
)
    N = length(x) + length(h) - 1
    y = zeros(Float64, N)

