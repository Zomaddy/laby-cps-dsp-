function rozwiazanie(;
    x::Vector{Float64} = [0.85, -1.72, 0.04, 4.43, 0.57, -0.05, -4.21, -2.48, 2.1, 1.17, -1.29, 3.34, -2.79, -4.93, 2.71, -1.41, 4.55, -4.92, -1.85, 4.88, -3.35, -0.67, 2.18, -0.22, -1.34, 3.71, -2.44, 1.22, -0.33, -2.72, -4.16, -3.2, -3.97, 1.32, 2.88, -3.8, -3.65, -2.81, 2.74, 3.57, 3.26, -3.76, -0.78, 1.76, 2.32, -4.64, -1.2, 2.05, -0.44, -1.99, -0.77, -1.42, -3.55, 0.5, -3.25, -4.72, -4.26, -3.71, 3.23, -1.58, 0.25],
    h::Vector{Float64} = [0.22, 3.41, 0.74, 4.79, -2.74, 2.18, 3.27, -0.52, -3.4, -3.44],
)

    N = length(x) + length(h) - 1
    y = zeros(Float64, N)

    for i in 1:length(x)
        for j in 1:length(h)
            y[i + j - 1] += x[i] * h[j]
        end
    end

    energy = sum(y .^ 2)
    return energy
end

