function rozwiazanie(;
    b::Vector{Float64} = [0.22260428984077194, -1.43457026032803, 4.811048712361645, -10.50465812901615, 16.391809795306504, -18.931993021285198, 16.391809795306504, -10.50465812901615, 4.811048712361645, -1.43457026032803, 0.22260428984077194],
    a::Vector{Float64} = [1.0, -4.690494715203397, 11.255249060507397, -17.77267136126449, 20.14944829286013, -16.701634938445387, 9.934510459421126, -3.8694979509406306, 0.624766882565444, 0.2238491658803432, -0.11304910033624699],
    x::Vector{Float64} = [-0.53, 0.67, -0.69, -0.3, -0.91, -0.57, -0.24, -0.44, 0.98, -0.12, -0.25, 0.42, 0.09, 0.41, -0.07, 0.01, 0.02, 0.23, -0.5, 0.81, 0.72, 0.91, 0.76, 0.67, 0.66, 0.25, -0.31, 0.63, 0.16, -0.96, 0.38],
    L::Int = 72,
)
    y = zeros(Float64, L)

    for n in 1:L
        sum_x = 0.0

        for m in 1:length(b)
            idx_x = n - m + 1
        
            if 1 <= idx_x <= length(x)
                sum_x += b[m] * x[idx_x]
            end
        end

        sum_y = 0.0

        for k in 2:length(a)
            idx_y = n - k + 1

            if 1 <= idx_y
                sum_y += a[k] * y[idx_y]
            end
        end

        y[n] = (sum_x - sum_y) / a[1]
    end

    energy = sum(y .^ 2)
    return energy
end

