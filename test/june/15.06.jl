function rozwiazanie(;
    x::Vector{Float64} = [2.97, 3.83, 1.99, -4.25, -2.75, 4.06, 3.89, -3.8, 0.09, -3.87, -0.74, 1.61, 2.87, -4.42, -0.98, -1.69, -1.52, -4.05, -4.21, -3.09, -1.21, -1.54, -1.63, 4.05, -0.96, -3.79, 2.62, -4.92, 3.04, -2.02, -2.19, 3.68, -0.86, -4.29, -1.74, 4.73, 4.03, 0.32, -2.5, 0.21, -4.28, -3.36, -0.28, -1.73, -4.04, -4.52, -1.1, 3.61, 0.76, 2.08, -3.39, 4.72, -2.1, 2.11, 0.92, 2.99, -1.75, -2.12, 4.86, 2.75, -2.63, 4.79, 1.84],
    h::Vector{Float64} = [-1.84, 2.27, 2.22, 4.63, -0.97, 2.4, 2.54, -0.45, 1.62, 4.16],
)
    N = length(x) + length(h) - 1
    y = zeros(Float64, N)

    for i in 1:length(x)
        for j in 1:length(h)
            y[i + j - 1] += x[i] * h[j]
        end
    end

    rms = sqrt(sum(y .^ 2) / N)
    return rms
end

