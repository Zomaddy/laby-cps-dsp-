)

    N = length(x) + length(h) - 1       #długość wyniku splotu

    y = zeros(Float64, N)               #utworzenie wektora wynikowego

    for i in 1:length(x)                #splot x * h

        for j in 1:length(h)

            y[i + j - 1] += x[i] * h[j]

        end
    end

    return sum(y) / N

end

