function rozwiazanie(;
    zz::Vector{ComplexF64} = ComplexF64[0.20744030217382925 - 0.9782476787777371im, 0.7126678102770087 + 0.7015016694170969im, 0.20744030217382925 + 0.9782476787777371im, 0.7126678102770087 - 0.7015016694170969im, 0.09257045648926909 - 0.9957061366614993im, 0.7658625431575472 + 0.6430043273480002im, 0.09257045648926909 + 0.9957061366614993im, 0.7658625431575472 - 0.6430043273480002im, -0.4818994147353125 - 0.876226542669054im, 0.925852610245106 + 0.3778848291507927im, -0.4818994147353125 + 0.876226542669054im, 0.925852610245106 - 0.3778848291507927im],
    pp::Vector{ComplexF64} = ComplexF64[0.6208252935232977 + 0.7423195553401403im, 0.317240329697893 - 0.9065136589159839im, 0.6208252935232977 - 0.7423195553401403im, 0.317240329697893 + 0.9065136589159839im, 0.5658758777492013 + 0.6930315115438856im, 0.30767523532908436 - 0.8183884486395173im, 0.5658758777492013 - 0.6930315115438856im, 0.30767523532908436 + 0.8183884486395173im, 0.4687307206754426 + 0.6612364966085713im, 0.35184383473609165 - 0.7119317281163414im, 0.4687307206754426 - 0.6612364966085713im, 0.35184383473609165 + 0.7119317281163414im],
    k::Float64 = 0.005366074582887813,
    F::Vector{Float64} = [0.17, 0.3, 0.37],
