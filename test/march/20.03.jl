   sum_phase = 0.0

   for f in F

        z = exp(2.0 * im * pi * f)

        num = prod(z .- zz)
        denum = prod(z .- pp)

        H_z = k * (num / denum)

        phase = angle(H_z)

        sum_phase += phase

   end

    return sum_phase / length(F)

end

