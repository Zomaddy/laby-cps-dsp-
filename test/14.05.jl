function rozwiazanie(;
    a::Float64 = -3.9,
    b::Float64 = 2.9,
    x::Vector{Float64} = [0.24, 0.91167, 1.58335, 2.25502, 2.9267, 2.80163, 2.12995, 1.45828, 0.7866, 0.11493, -0.55674, -1.22842, -1.90009, -2.57177, -3.24344, -3.91512, -3.81321, -3.14153, -2.46986, -1.79818, -1.12651, -0.45484, 0.21684, 0.88851, 1.56019, 2.23186, 2.90354, 2.82479, 2.15311, 1.48144, 0.80977, 0.13809, -0.53358, -1.20526, -1.87693, -2.54861, -3.22028, -3.89196, -3.83637, -3.16469, -2.49302, -1.82135, -1.14967, -0.478, 0.19368, 0.86535, 1.53703, 2.2087, 2.88038, 2.84795, 2.17628, 1.5046, 0.83293, 0.16125, -0.51042, -1.1821, -1.85377, -2.52545, -3.19712, -3.86879],
)
    n = 7
    poziomy_kwant = 2^n
    q = (b-a)/(poziomy_kwant-1)

    suma_blad_kw = 0.0

    N = length(x)

    for i in 1:N
        value = max(a, min(b,x[i]))
        index = round((value-a)/q)
        index = max(0.0, min(Float64(poziomy_kwant-1), index))

        x_q = a + index*q

        e = x_q - x[i]

        suma_blad_kw += e^2

    end

    energia_bledu = suma_blad_kw

    return energia_bledu


end
