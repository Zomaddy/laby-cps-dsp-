function rozwiazanie(;
    a::Float64 = -4.6,
    b::Float64 = 1.4,
    x::Vector{Float64} = [-4.6, -4.35191, -4.10383, -3.85574, -3.60766, -3.35957, -3.11149, -2.8634, -2.61531, -2.36723, -2.11914, -1.87106, -1.62297, -1.37489, -1.1268, -0.87871, -0.63063, -0.38254, -0.13446, 0.11363, 0.36172, 0.6098, 0.85789, 1.10597, 1.35406, -4.39786, -4.14977, -3.90168, -3.6536, -3.40551, -3.15743, -2.90934, -2.66126, -2.41317, -2.16508, -1.917, -1.66891, -1.42083, -1.17274, -0.92466, -0.67657, -0.42848, -0.1804, 0.06769, 0.31577, 0.56386, 0.81194, 1.06003, 1.30812, -4.4438, -4.19571, -3.94763, -3.69954, -3.45145, -3.20337, -2.95528, -2.7072, -2.45911, -2.21103, -1.96294, -1.71485, -1.46677, -1.21868, -0.9706, -0.72251, -0.47443, -0.22634, 0.02175, 0.26983, 0.51792, 0.766, 1.01409, 1.26217, -4.48974, -4.24165, -3.99357, -3.74548, -3.4974],
)
    n = 4
    poziomy_kwant = 2^n
    q = (b-a)/(poziomy_kwant - 1)

    suma_blad_kw = 0.0

    N = length(x)

    for i in 1:N
        value = max(a, min(b,x[i]))
        index = round((value - a)/q)
        index = max(0.0, min(Float64(poziomy_kwant-1), index))

        x_q = a + q*index

        e = x_q - x[i]

        suma_blad_kw += e^2

    end

    moc_bledu = suma_blad_kw/N

    return moc_bledu

end
